export function getRandomMessage(type, context = {}) {
  const lang = currentLanguage || 'es';
  const messages = PET_MESSAGES[lang]?.[type];
  if (!messages || messages.length === 0) return '';
  
  const message = messages[Math.floor(Math.random() * messages.length)];
  
  return message
    .replace('{gems}', context.gems || 0)
    .replace('{remaining}', context.remaining || 0)
    .replace('{nextPet}', context.nextPet || 'the next pet');
}

export function getNextPetInfo(currentGems, unlockedPets) {
  const PET_THRESHOLDS = [
    { id: 'luna', name: 'Luna 🐱', threshold: 10 },
    { id: 'max', name: 'Max 🐶', threshold: 25 },
    { id: 'rocco', name: 'Rocco 🦊', threshold: 40 },
    { id: 'draco', name: 'Draco 🐉', threshold: 60 },
    { id: 'sparkle', name: 'Sparkle 🦄', threshold: 100 }
  ];
  
  for (const pet of PET_THRESHOLDS) {
    if (!unlockedPets.includes(pet.id) && currentGems < pet.threshold) {
      return {
        name: pet.name,
        threshold: pet.threshold,
        remaining: pet.threshold - currentGems
      };
    }
  }
  
  return null;
}

let currentLanguage = 'es';

export function initI18n() {
  const browserLang = navigator.language.split('-')[0];
  const savedLang = localStorage.getItem('language');
  currentLanguage = savedLang || (browserLang in translations ? browserLang : 'es');
  
  applyTranslations(currentLanguage);
  
  createLanguageSelector(currentLanguage);
}

export function applyTranslations(lang) {
  if (!(lang in translations)) {
    console.warn(`Idioma no soportado: ${lang}`);
    return;
  }
  
  currentLanguage = lang;
  
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (translations[lang][key]) {
      element.textContent = translations[lang][key];
    }
  });
  
  localStorage.setItem('language', lang);
}

function createLanguageSelector(currentLang) {
  if (document.getElementById('language-selector')) {
    return;
  }
  
  const selector = document.createElement('select');
  selector.id = 'language-selector';
  selector.className = 'language-selector';
  selector.setAttribute('aria-label', 'Select language');
  
  const languages = [
    { code: 'es', name: 'Español' },
    { code: 'en', name: 'English' }
  ];
  
  languages.forEach(lang => {
    const option = document.createElement('option');
    option.value = lang.code;
    option.textContent = lang.name;
    if (lang.code === currentLang) {
      option.selected = true;
    }
    selector.appendChild(option);
  });
  
  selector.addEventListener('change', (e) => {
    applyTranslations(e.target.value);
  });
  
  document.body.appendChild(selector);
}

export function getCurrentLanguage() {
  return currentLanguage;
}
